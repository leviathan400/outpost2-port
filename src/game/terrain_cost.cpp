int terrainMoveCost(int cellType, int moveClass) {
    if (cellType < 0 || cellType >= kNumCellTypes) return 0;
    if (moveClass < 0 || moveClass >= kNumMoveClasses) return 0;
    return kTerrainMoveCost[cellType][moveClass];
}

