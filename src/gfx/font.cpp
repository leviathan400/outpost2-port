static void drawGlyph(uint32_t* fb, int fbW, int fbH, char ch, int px, int py, uint32_t color) {
    if (ch < 32 || ch > 126) return;
    const uint8_t* glyph = g_font8x12[ch - 32];

    for (int row = 0; row < 12; ++row) {
        int y = py + row;
        if (y < 0 || y >= fbH) continue;
        uint8_t bits = glyph[row];
        for (int col = 0; col < 8; ++col) {
            int x = px + col;
            if (x >= 0 && x < fbW && (bits & (0x80 >> col))) {
                fb[y * fbW + x] = color;
            }
        }
    }
}

int Font::getTextWidth(const std::string& text) {
    int len = 0;
    for (char c : text) {
        if (c != '&') len++; // Skip Windows accelerator prefix '&'
    }
    return len * 8;
}

int Font::getTextHeight() {
    return 12;
}

void Font::drawText(uint32_t* fb, int fbW, int fbH,
                    const std::string& text, int x, int y,
                    uint32_t color, bool shadow, uint32_t shadowColor) {
    if (shadow) {
        int sx = x + 1;
        int sy = y + 1;
        for (char c : text) {
            if (c == '&') continue;
            drawGlyph(fb, fbW, fbH, c, sx, sy, shadowColor);
            sx += 8;
        }
    }

    int curX = x;
    for (size_t i = 0; i < text.size(); ++i) {
        char c = text[i];
        if (c == '&') continue; // Skip accelerator '&'
        drawGlyph(fb, fbW, fbH, c, curX, y, color);
        curX += 8;
    }
}

void Font::drawTextCentered(uint32_t* fb, int fbW, int fbH,
                            const std::string& text, int centerX, int y,
                            uint32_t color, bool shadow, uint32_t shadowColor) {
    int w = getTextWidth(text);
    int startX = centerX - (w / 2);
    drawText(fb, fbW, fbH, text, startX, y, color, shadow, shadowColor);
}

